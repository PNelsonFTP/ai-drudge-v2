// Open, update or close ONE GitHub issue from the validate-feeds verdict JSON. Deduped on the title
// prefix "Feed audit:" so the weekly run never opens a second issue while one is open.
//
// Env:
//   VALIDATE_OUT              path of the verdict JSON written by validate-feeds
//   GH_TOKEN / GITHUB_TOKEN   for the gh CLI (Actions provides it)
//   GITHUB_REPOSITORY         owner/name (Actions provides it)
//
// Never fails the workflow because gh is missing or the verdict file is unreadable.

import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { summarize, type Verdict } from "./feedVerdict";

export const TITLE_PREFIX = "Feed audit:";

/**
 * Feed-controlled text (Content-Type notes, redirect targets, even names from a candidate list) goes
 * into a Markdown issue body: neutralise markup and mentions, and keep it on one line.
 */
export function mdSafe(value: string | undefined | null, max = 200): string {
  return (value ?? "")
    .replace(/[\r\n\t]+/g, " ")
    .replace(/[`<>[\]|*_~!]/g, "")
    .replace(/@/g, "@​")
    .trim()
    .slice(0, max);
}

/** Verdict strings are our own vocabulary (OK, HTTP_404, NOT_FEED ...); anything else in the file is not trusted. */
function verdictLabel(verdict: string): string {
  return /^[A-Z][A-Z0-9_]{1,19}$/.test(verdict) ? verdict : "UNKNOWN";
}

/**
 * URLs and failure notes are shown as inert code spans, never as links the reader is told to follow:
 * inside a code span GitHub renders no Markdown and autolinks nothing (bare URLs, #123, @mentions).
 * Notes go through mdSafe first (belt and braces); mdSafe alone left "see https://evil.example/fix
 * and #1" in plain text, which GitHub turns into links.
 */
function mdCode(value: string | undefined | null, max = 300): string {
  // eslint-disable-next-line no-control-regex
  return `\`${(value ?? "").replace(/[`\u0000-\u001f\u007f]+/g, " ").trim().slice(0, max)}\``;
}

/**
 * GitHub rejects an issue body over 65,536 characters. On a mass-failure day (every source failing
 * with a 200-character note) the full list is ~170,000 - and `gh issue create` would fail on exactly
 * the day the issue matters. The lists are cut to this budget and say how many rows were left out.
 */
export const ISSUE_BODY_BUDGET = 60_000;

export function formatIssueBody(verdicts: readonly Verdict[], updatedAt: string): string {
  const { actionable, transient, moved } = summarize(verdicts);
  const lines: string[] = [
    `_Updated ${mdSafe(updatedAt, 40)}_`,
    "",
    "Generated by the weekly feed-audit workflow from `scripts/tools/validate-feeds.ts` (feeds, scrape pages and JSON APIs). Transient Reddit / hnrss / Substack / rate-limit failures are listed separately and are usually safe to ignore.",
    "",
  ];
  let used = lines.join("\n").length;
  // One list under a heading; rows that no longer fit the budget are counted, not written.
  const section = (heading: string, intro: string | null, rows: string[]): void => {
    if (rows.length === 0) return;
    lines.push(heading, "");
    if (intro) lines.push(intro, "");
    let shown = 0;
    for (const row of rows) {
      if (used + row.length + 1 > ISSUE_BODY_BUDGET) break;
      lines.push(row);
      used += row.length + 1;
      shown++;
    }
    if (shown < rows.length) lines.push(`- ...and ${rows.length - shown} more (see \`feed-audit.json\` in the run's \`v2-audit-reports\` artifact)`);
    lines.push("");
  };

  section(
    `## Actionable (${actionable.length})`,
    null,
    actionable.map((v) => {
      const extra = [mdSafe(v.note) ? mdCode(mdSafe(v.note), 200) : null, v.newestAgeDays != null ? `newest ${Number(v.newestAgeDays)}d` : null, v.itemCount != null ? `${Number(v.itemCount)} items` : null].filter(Boolean).join(", ");
      return `- **${verdictLabel(v.verdict)}** - ${mdSafe(v.name)} - ${mdCode(v.url)}${extra ? ` (${extra})` : ""}`;
    }),
  );
  section(
    `## Answered from another host (${moved.length})`,
    "Verify each new location by hand before changing the registry - a redirect target is not proof of a legitimate move:",
    moved.map((v) => `- ${mdSafe(v.name)}: ${mdCode(v.url)} now answers from ${mdCode(v.finalUrl)}`),
  );
  section(
    `## Transient / known-benign (${transient.length})`,
    null,
    transient.map((v) => `- **${verdictLabel(v.verdict)}** - ${mdSafe(v.name)}`),
  );
  lines.push("Fix: edit the source in `scripts/registry/sources/`, then run `npx tsx scripts/tools/validate-feeds.ts`.");
  return lines.join("\n");
}

export interface IssuePlan {
  action: "none" | "close" | "create" | "edit";
  title?: string;
  body?: string;
}

/** What to do with the audit issue, given the verdicts and whether one is already open. Pure. */
export function planIssue(verdicts: readonly Verdict[], hasOpenIssue: boolean, updatedAt: string): IssuePlan {
  const { actionable, moved } = summarize(verdicts);
  const problems = actionable.length + moved.length;
  if (problems === 0) return { action: hasOpenIssue ? "close" : "none" };
  return {
    action: hasOpenIssue ? "edit" : "create",
    title: `${TITLE_PREFIX} ${problems} problem${problems === 1 ? "" : "s"}`,
    body: formatIssueBody(verdicts, updatedAt),
  };
}

export interface OpenIssue {
  number: number;
  title: string;
}

/**
 * `gh` arguments that list the open issues of the repository as lines `<number><TAB><title>`: issues
 * only (no pull requests), opened by a BOT account, whose title starts with the audit prefix. Same
 * listing as the other rolling issues of refresh.yml / feed-audit.yml: the audit must never adopt -
 * edit or close - an issue a person opened under a look-alike title.
 */
export function lookupArgs(repository: string | undefined): string[] {
  const repo = repository && /^[\w.-]+\/[\w.-]+$/.test(repository) ? repository : "{owner}/{repo}";
  const filter = `.[] | select(.pull_request == null and .user.type == "Bot" and (.title | startswith("${TITLE_PREFIX}"))) | "\\(.number)\\t\\(.title)"`;
  return ["api", "--paginate", `repos/${repo}/issues?state=open&per_page=100`, "--jq", filter];
}

/** The open audit issue (lowest number first), or null. Throws when the listing fails or a line is not `<number><TAB><title>`. */
export function findAuditIssue(args: string[], run: (args: string[]) => string): OpenIssue | null {
  const found: OpenIssue[] = [];
  for (const line of run(args).split("\n")) {
    if (!line.trim()) continue;
    const m = /^(\d+)\t(.*)$/.exec(line);
    if (!m) throw new Error(`unexpected line in the issue listing: ${JSON.stringify(line.slice(0, 80))}`);
    if (m[2].startsWith(TITLE_PREFIX)) found.push({ number: Number(m[1]), title: m[2] });
  }
  found.sort((a, b) => a.number - b.number);
  return found[0] ?? null;
}

/** A failed issue lookup stops the step in GitHub Actions and is only a warning anywhere else. */
export function lookupFailureIsFatal(env: Record<string, string | undefined>): boolean {
  return env.GITHUB_ACTIONS === "true";
}

function gh(args: string[]): string {
  return execFileSync("gh", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

async function main(): Promise<void> {
  const path = process.env.VALIDATE_OUT;
  if (!path) {
    console.log("report-feed-audit: VALIDATE_OUT not set - skipping");
    return;
  }
  let verdicts: Verdict[];
  try {
    const parsed: unknown = JSON.parse(await readFile(path, "utf8"));
    if (!Array.isArray(parsed)) throw new Error("verdict file is not an array");
    verdicts = parsed as Verdict[];
  } catch (e) {
    console.warn("report-feed-audit: could not read verdicts:", e instanceof Error ? e.message : e);
    return;
  }

  let existing: OpenIssue | null = null;
  try {
    existing = findAuditIssue(lookupArgs(process.env.GITHUB_REPOSITORY), gh);
  } catch (e) {
    // In CI the issue is the ONLY signal of a dead feed (feed-audit.yml never fails the run on
    // one), so a lookup that fails there must fail this step - the workflow's last step then fails
    // the run. Outside CI there is no token and nothing to report to.
    if (lookupFailureIsFatal(process.env)) throw e;
    console.warn("report-feed-audit: issue lookup failed (expected outside CI):", e instanceof Error ? e.message : e);
    return;
  }

  const plan = planIssue(verdicts, existing !== null, new Date().toISOString());
  if (plan.action === "none") {
    console.log("Audit clean - no issue to open");
  } else if (plan.action === "close" && existing) {
    gh(["issue", "close", String(existing.number), "--comment", "Latest feed audit is clean. Closing."]);
    console.log(`Closed issue #${existing.number} - audit clean`);
  } else if (plan.action === "edit" && existing && plan.title && plan.body) {
    gh(["issue", "edit", String(existing.number), "--title", plan.title, "--body", plan.body]);
    console.log(`Updated issue #${existing.number}: ${plan.title}`);
  } else if (plan.title && plan.body) {
    gh(["issue", "create", "--title", plan.title, "--body", plan.body]);
    console.log(`Opened issue: ${plan.title}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error("report-feed-audit failed:", e);
    process.exit(1);
  });
}
